"""
Result files -> the paper's tables and numbers.

    python -m eval.tables

Reads data/eval_results/**.json and writes

    paper/tables/*.tex     booktabs tables, each headed by a comment naming the result file,
                           the commit and the machine that produced it
    paper/tables/numbers.tex   \\newcommand macros for every number quoted in the text

A table whose results do not exist yet is simply not written; the paper \\input's each one
through \\IfFileExists and prints "[pending]" instead. So the paper never contains a number
that no script produced.
"""

import json
import sys
from pathlib import Path
from typing import Dict, List, Optional

from eval.common import PAPER_DIR, RESULTS_DIR

TABLES = PAPER_DIR / "tables"


def _load(relative: str) -> Optional[Dict]:
    path = RESULTS_DIR / relative
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _header(relative: str, data: Dict) -> str:
    prov = data.get("provenance") or {}
    machine = (prov.get("machine") or {})
    return (f"% Generated by eval/tables.py from data/eval_results/{relative}\n"
            f"% commit {prov.get('git_commit', '?')[:10]}{' (dirty)' if prov.get('git_dirty') else ''}"
            f" | {machine.get('cpu', '?')} | {machine.get('platform', '?')}"
            f" | {prov.get('timestamp', '?')}\n")


def _f(value, digits=3, pct=False) -> str:
    if value is None:
        return "--"
    if pct:
        return f"{100 * value:.1f}"
    return f"{value:.{digits}f}"


def _bold_best(values: List[Optional[float]], higher=True) -> List[bool]:
    present = [v for v in values if v is not None]
    if not present:
        return [False] * len(values)
    best = max(present) if higher else min(present)
    return [v is not None and abs(v - best) < 1e-12 for v in values]


def _write(name: str, text: str) -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / name).write_text(text, encoding="utf-8")
    print(f"  wrote paper/tables/{name}")


NAMES = {"legacy": "Legacy union", "dense": "Dense", "bm25": "BM25 (server)",
         "rrf": "RRF (dense+BM25)", "dbsf": "DBSF (dense+BM25)"}


def ir_table(numbers: Dict) -> None:
    data = _load("ir/ir_bench.json")
    if not data:
        return
    table = data["table"]
    strategies = [s for s in data["strategies"] if s in table]
    cols = [("", "all", "r@3"), ("", "all", "ndcg@10"), ("", "para", "ndcg@10"),
            ("+rerank", "all", "r@3"), ("+rerank", "all", "ndcg@10"),
            ("+rerank", "para", "ndcg@10")]
    grid = {s: [table[s + suffix][subset][metric]["mean"] for suffix, subset, metric in cols]
            for s in strategies}
    bold = {s: [False] * len(cols) for s in strategies}
    for c in range(len(cols)):
        flags = _bold_best([grid[s][c] for s in strategies])
        for s, flag in zip(strategies, flags):
            bold[s][c] = flag
    lines = [_header("ir/ir_bench.json", data),
             "\\begin{tabular}{@{}lcccccc r@{}}\n\\toprule\n",
             " & \\multicolumn{3}{c}{First stage} & \\multicolumn{3}{c}{+ Rerank} & \\\\\n",
             "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\n",
             "Retriever & R@3 & nDCG & nDCG$_{\\text{para}}$ & R@3 & nDCG & "
             "nDCG$_{\\text{para}}$ & p50 ms \\\\\n\\midrule\n"]
    for s in strategies:
        cells = [f"\\textbf{{{_f(v)}}}" if b else _f(v) for v, b in zip(grid[s], bold[s])]
        latency = table[s]["latency_ms"]["first_stage"]["p50"]
        lines.append(f"{NAMES.get(s, s)} & " + " & ".join(cells) + f" & {_f(latency, 1)} \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    _write("ir.tex", "".join(lines))

    n = data["n_queries"]
    numbers["IRQueries"] = str(n)
    if "rrf+rerank" in table and "legacy+rerank" in table:
        new = table["rrf+rerank"]["all"]["ndcg@10"]["mean"]
        old = table["legacy+rerank"]["all"]["ndcg@10"]["mean"]
        numbers["IRRrfNdcg"] = _f(new)
        numbers["IRLegacyNdcg"] = _f(old)
        numbers["IRNdcgGainPct"] = _f((new - old) / old if old else None, pct=True)
        numbers["IRRrfRThree"] = _f(table["rrf+rerank"]["all"]["r@3"]["mean"], pct=True)
        numbers["IRLegacyRThree"] = _f(table["legacy+rerank"]["all"]["r@3"]["mean"], pct=True)
        sig = data["significance"].get("rrf+rerank|ndcg@10|all")
        if sig:
            numbers["IRRrfPValue"] = f"{sig['p_value']:.3f}"
    if "rrf" in table and "legacy" in table:
        numbers["IRRrfLatency"] = _f(table["rrf"]["latency_ms"]["first_stage"]["p50"], 1)
        numbers["IRLegacyLatency"] = _f(table["legacy"]["latency_ms"]["first_stage"]["p50"], 1)
    mode = data.get("mode", {}).get("rrf")
    if mode:
        numbers["ModeAccuracy"] = _f(mode["accuracy"], pct=True)


def scaling_table(numbers: Dict) -> None:
    data = _load("ir/ir_scaling.json")
    if not data:
        return
    lines = [_header("ir/ir_scaling.json", data),
             "\\begin{tabular}{@{}rrrrr@{}}\n\\toprule\n",
             "Chunks & In-proc.\\ BM25 & cold build & Qdrant BM25 & Qdrant RRF \\\\\n",
             " & ms/query & ms & ms/query & ms/query \\\\\n\\midrule\n"]
    for row in data["document_size"]:
        lines.append(f"{row['chunks']:,} & {_f(row['legacy_bm25_ms']['p50'], 2)} & "
                     f"{_f(row['legacy_cold_build_ms'], 0)} & "
                     f"{_f(row['qdrant_bm25_ms']['p50'], 2)} & "
                     f"{_f(row['qdrant_rrf_ms']['p50'], 2)} \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    _write("scaling.tex", "".join(lines))
    rows = data["document_size"]
    if rows:
        big = rows[-1]
        numbers["ScaleChunks"] = f"{big['chunks']:,}"
        numbers["ScaleLegacyMs"] = _f(big["legacy_bm25_ms"]["p50"], 1)
        numbers["ScaleQdrantMs"] = _f(big["qdrant_bm25_ms"]["p50"], 1)
        numbers["ScaleColdMs"] = _f(big["legacy_cold_build_ms"], 0)
    tenants = data.get("tenants") or []
    if tenants:
        numbers["TenantDocs"] = f"{tenants[-1]['documents']:,}"
        numbers["TenantRrfMs"] = _f(tenants[-1]["qdrant_rrf_ms"]["p50"], 1)
        numbers["TenantRrfMsSmall"] = _f(tenants[0]["qdrant_rrf_ms"]["p50"], 1)


def cache_table(numbers: Dict) -> None:
    data = _load("cache/cache_bench.json")
    if not data:
        return
    chosen = data["chosen"]
    rows = [("Embedding only", chosen["embedding_only"]["tau"], None,
             chosen["embedding_only"]["test"])]
    matched = chosen.get("embedding_only_matched_precision")
    if matched:
        rows.append(("Embedding only, same precision", matched["tau"], None, matched))
    rows.append(("Verified (ours)", chosen["verified"]["tau"],
                 chosen["verified"]["verifier_threshold"], chosen["verified"]["test"]))
    lines = [_header("cache/cache_bench.json", data),
             "\\begin{tabular}{@{}lccccc@{}}\n\\toprule\n",
             "Hit rule & $\\tau$ & Prec. & Recall & F1 & False hits \\\\\n\\midrule\n"]
    for name, tau, verifier, test in rows:
        label = name + (f" ($v\\geq{verifier}$)" if verifier is not None else "")
        lines.append(f"{label} & {tau:.2f} & {_f(test['precision'])} & {_f(test['recall'])} "
                     f"& {_f(test['f1'])} & {_f(test['false_hit_rate_neg'], pct=True)}\\% \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    _write("cache.tex", "".join(lines))
    v = chosen["verified"]["test"]
    e = chosen["embedding_only"]["test"]
    numbers.update({
        "CacheTau": f"{chosen['verified']['tau']:.2f}",
        "CachePrecision": _f(v["precision"], pct=True),
        "CacheRecall": _f(v["recall"], pct=True),
        "CacheFalseHit": _f(v["false_hit_rate_neg"], pct=True),
        "CacheEmbPrecision": _f(e["precision"], pct=True),
        "CacheEmbFalseHit": _f(e["false_hit_rate_neg"], pct=True),
        "CacheLookupMs": _f(data["latency_ms"]["lookup"]["p50"], 0),
        "CacheEntries": str(data["cached_entries"]),
    })
    replay = _load("cache/cache_replay.json")
    if replay:
        full = next((r for r in replay["runs"] if r["accept_rate"] == 1.0), replay["runs"][0])
        numbers["ReplayHitRate"] = _f(full["hit_rate"], pct=True)
        numbers["ReplayHitPrecision"] = _f(full["hit_precision"], pct=True)
        numbers["ReplayAsks"] = str(full["asks"])
        measured = [r for r in replay["runs"] if r["accept_rate"] != 1.0]
        if measured:
            numbers["ReplayHitRateMeasured"] = _f(measured[0]["hit_rate"], pct=True)
            numbers["ReplayAcceptRate"] = _f(measured[0]["accept_rate"], pct=True)
    latency = _load("cache/chat_latency.json")
    if latency:
        numbers["TurnMissS"] = _f((latency["miss_ms"]["p50"] or 0) / 1000, 1)
        numbers["TurnHitS"] = _f((latency["hit_ms"]["p50"] or 0) / 1000, 2)
        machine = (latency.get("provenance") or {}).get("machine", {})
        numbers["TurnMachine"] = (machine.get("cpu") or "?").replace("_", " ")
        if latency.get("judge_pass_rate") is not None:
            numbers["JudgePassRate"] = _f(latency["judge_pass_rate"], pct=True)


def load_table(numbers: Dict) -> None:
    runs = sorted((RESULTS_DIR / "load").glob("load_*.json")) if (RESULTS_DIR / "load").exists() \
        else []
    if not runs:
        return
    lines = ["% Generated by eval/tables.py from data/eval_results/load/load_*.json\n",
             "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n",
             "Configuration & Users & Chats/min & p50 s & p95 s & Hits \\\\\n\\midrule\n"]
    for path in runs:
        data = json.loads(path.read_text(encoding="utf-8"))
        for level in data["levels"]:
            lines.append(f"{data['label'].replace('_', '+')} & {level['users']} & "
                         f"{_f(level['throughput_per_min'], 2)} & "
                         f"{_f((level['e2e_ms']['p50'] or 0) / 1000, 1)} & "
                         f"{_f((level['e2e_ms']['p95'] or 0) / 1000, 1)} & "
                         f"{_f(level['cache_hit_rate'], pct=True)}\\% \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    _write("load.tex", "".join(lines))


def probe_table(numbers: Dict) -> None:
    data = _load("serving/probe.json")
    if not data:
        return
    reports = data if isinstance(data, list) else data.get("reports", [])
    lines = ["% Generated by eval/tables.py from data/eval_results/serving/probe.json\n",
             "\\begin{tabular}{@{}lrrr@{}}\n\\toprule\n",
             "Server & Concurrent & Aggregate tok/s & Speed-up \\\\\n\\midrule\n"]
    for report in reports:
        batching = report.get("batching") or []
        if not batching:
            continue
        base = batching[0]["aggregate_tok_s"] or 1
        for row in batching:
            lines.append(f"{report['server']} & {row['concurrency']} & "
                         f"{_f(row['aggregate_tok_s'], 1)} & "
                         f"{_f(row['aggregate_tok_s'] / base, 2)}$\\times$ \\\\\n")
        numbers[f"Batch{report['server'].capitalize()}Speedup"] = \
            _f(batching[-1]["aggregate_tok_s"] / base, 1)
        numbers[f"Batch{report['server'].capitalize()}Slots"] = str(batching[-1]["concurrency"])
    lines.append("\\bottomrule\n\\end{tabular}\n")
    _write("serving.tex", "".join(lines))


def heatmap_table(numbers: Dict) -> None:
    data = _load("insights/heatmap_bench.json")
    if not data:
        return
    s = data["summary"]
    lines = [_header("insights/heatmap_bench.json", data),
             "\\begin{tabular}{@{}lr@{}}\n\\toprule\nMeasure & Value \\\\\n\\midrule\n",
             f"Topic NMI / ARI (clustered questions) & {_f(s['nmi'])} / {_f(s['ari'])} \\\\\n",
             f"Topic NMI / ARI (noise as singletons) & {_f(s['nmi_noise_singletons'])} / "
             f"{_f(s['ari_noise_singletons'])} \\\\\n",
             f"Questions assigned to a topic & {_f(s['clustered_share'], pct=True)}\\% \\\\\n",
             f"Page attribution, exact / $\\pm$1 page & {_f(s['attribution_exact'], pct=True)}\\%"
             f" / {_f(s['attribution_within_1'], pct=True)}\\% \\\\\n",
             f"Planted pages in top-3 & {_f(s['planted_recall_at_3'], pct=True)}\\% \\\\\n"]
    scaling = data.get("scaling") or []
    if scaling:
        last = scaling[-1]
        lines.append(f"Mining time, {last['questions']:,} questions & "
                     f"{_f(last['total_ms'] / 1000, 2)} s \\\\\n")
    lines.append("\\bottomrule\n\\end{tabular}\n")
    _write("heatmap.tex", "".join(lines))
    numbers.update({"HeatNMI": _f(s["nmi"]), "HeatARI": _f(s["ari"]),
                    "HeatClustered": _f(s["clustered_share"], pct=True),
                    "HeatAttribution": _f(s["attribution_exact"], pct=True),
                    "HeatAttributionNear": _f(s["attribution_within_1"], pct=True),
                    "HeatPlanted": _f(s["planted_recall_at_3"], pct=True),
                    "HeatTurns": f"{data['turns']:,}"})
    if scaling:
        numbers["HeatScaleN"] = f"{scaling[-1]['questions']:,}"
        numbers["HeatScaleS"] = _f(scaling[-1]["total_ms"] / 1000, 1)


def workload_numbers(numbers: Dict) -> None:
    from eval.common import CORPUS_DIR, WORKLOAD_DIR, read_jsonl

    corpus = CORPUS_DIR / "corpus.json"
    if corpus.exists():
        data = json.loads(corpus.read_text(encoding="utf-8"))
        docs = data["documents"]
        numbers["CorpusDocs"] = str(len(docs))
        numbers["CorpusPages"] = str(sum(d.get("n_pages") or 0 for d in docs))
        numbers["CorpusChunks"] = str(sum(d.get("n_chunks") or 0 for d in docs))
    families = read_jsonl(WORKLOAD_DIR / "families.jsonl")
    if families:
        numbers["WorkloadFamilies"] = str(len(families))
        numbers["WorkloadQuestions"] = str(4 * len(families))
    manifest = WORKLOAD_DIR / "manifest.json"
    if manifest.exists():
        m = json.loads(manifest.read_text(encoding="utf-8"))
        numbers["WorkloadStudents"] = str(m["students"])
        numbers["WorkloadAsks"] = str(m["n_asks"])


def main() -> int:
    numbers: Dict[str, str] = {}
    for build in (workload_numbers, ir_table, scaling_table, cache_table, load_table,
                  probe_table, heatmap_table):
        build(numbers)
    lines = ["% Generated by eval/tables.py -- every number quoted in the text.\n"]
    for name, value in sorted(numbers.items()):
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}\n")
    _write("numbers.tex", "".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
